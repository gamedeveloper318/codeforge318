export const DEFAULT_FILE_ICON = "file";
export const FOLDER_ICON = "folder";
export const FOLDER_OPEN_ICON = "folder-open";

/** The icon id for a file name or path (e.g. "app.py" -> "python"). */
export function iconForFile(fileName: string): string {
  const name = (fileName.split(/[\\/]/).pop() ?? fileName).toLowerCase();
  const exact = FILE_NAMES[name];
  if (exact) return exact;
  if (name.startsWith(".env")) return "tune";
  if (name.startsWith("dockerfile") || name.endsWith(".dockerfile")) return "docker";
  // Try "a.test.ts" -> "test.ts" before "ts".
  const parts = name.split(".");
  for (let i = 1; i < parts.length; i++) {
    const icon = EXTENSIONS[parts.slice(i).join(".")];
    if (icon) return icon;
  }
  return DEFAULT_FILE_ICON;
}

/** Every icon id this module can return (the copy script and tests use it). */
export function allIconIds(): string[] {
  return [
    ...new Set([
      ...Object.values(FILE_NAMES),
      ...Object.values(EXTENSIONS),
      "tune",
      "docker",
      DEFAULT_FILE_ICON,
      FOLDER_ICON,
      FOLDER_OPEN_ICON,
    ]),
  ].sort();
}
